%% LOCAL FUNCTION
function [x, u] = flatAt(mp, shape, t)
    [s, ds, dds, ddds, dddds] = shape.get_flat_outputs(t);
    [x, u] = A02_FlatnessMap.map(mp, s, ds, dds, ddds, dddds);
end

function maintain_timing(tic_start, next_deadline)
    sleep_time = next_deadline - toc(tic_start);
    if sleep_time > 0
        pause(sleep_time);
    end
end

function dt = compute_dt(t_now, last_time, iteration, dt_nominal)
    if iteration == 1
        dt = dt_nominal;
    else
        dt = t_now - last_time;
    end
end