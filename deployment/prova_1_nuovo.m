%% v2_OpenLoop_Test_Shapes_Setpoints
% Reference (flatness) vs MATLAB (ODE + ZOH) vs drone (position setpoints)
% Frames: NED / FRD

clear; clc; close all;

%% PATHS
addpath('models');
addpath('flatness');
addpath('configs');
addpath('trajectories');
addpath('utils');
addpath('deployment');


%% SETUP
mp = ModelParameters;
cp = ControlParameters;
tp = TrajectoryParameters;

Ts    = cp.Ts;
ns    = '/antx';
p0    = [0; 0; -1];
psi0  = 0;

model   = A02_SimplifiedModel_Deployment(mp);
ode_opt = odeset('RelTol', 1e-10, 'AbsTol', 1e-12);

SHAPE = 'Circle';  % 'Circle' | 'Roll' | 'Yaw' | 'Thrust'

switch SHAPE
    case 'Circle'
        shape = ShapeCircleDeployment(tp.CircleDeployment);
        T_duration = tp.T_duration_circle_deployment();

    case 'Roll'
        shape = ShapeRollTest(tp.Roll);
        T_duration = tp.T_duration_roll;

    case 'Yaw'
        shape = ShapeYawTest(tp.Yaw);
        T_duration = tp.T_duration_yaw;

    case 'Thrust'
        shape = ShapeThrustTest(tp.Thrust);
        T_duration = tp.T_duration_thrust;

    otherwise
        error('Unknown shape: %s', SHAPE);
end

t_k = 0:Ts:T_duration;
N   = numel(t_k) - 1;


%% 1. CONTINUOUS REFERENCE FROM FLATNESS
% Dense sampling used only to plot the continuous reference.

t_ref = linspace(0, T_duration, max(2000, 100*N));

X_ref = zeros(12, numel(t_ref));

for i = 1:numel(t_ref)
    X_ref(:,i) = flatAt(mp, shape, t_ref(i));
end

X_ref(9,:) = unwrap(X_ref(9,:));


%% 2. MATLAB SIMULATION: SAMPLED INPUT + ZOH
% Sample the flatness map every Ts.
% Hold each input constant for Ts and integrate the nonlinear model.

X_sample = zeros(12, N+1);
U_sample = zeros(4, N+1);

for k = 1:N+1
    [X_sample(:,k), U_sample(:,k)] = flatAt(mp, shape, t_k(k));
end

X_sample(9,:) = unwrap(X_sample(9,:));

X_matlab = zeros(12, N+1);
X_matlab(:,1) = X_sample(:,1);

for k = 1:N
    [~, x_ode] = ode45( ...
        @(t,x) model.dynamics(t, x, U_sample(:,k)), ...
        [t_k(k), t_k(k+1)], X_matlab(:,k), ode_opt);

    X_matlab(:,k+1) = x_ode(end,:)';
end


%% 3. DRONE DEPLOYMENT
% Send the same sampled position setpoints generated by MATLAB.
% Log the measured drone position whenever available.

X_drone = nan(12, N+1);
t_drone = nan(1, N+1);

try
    Drone.startup_sitl();

    drone = Drone(ns);
    drone.connect();
    drone.arm();
    pause(2);

    drone.takeoff(p0(3));
    pause(5);

    drone.sendPositionSetpoint(p0, psi0);
    pause(5);

    dt = 0.1;

    iteration = 0;
    n_samples = 0;
    tic_start = tic;
    next_deadline = dt;
    last_time = 0;
    point = 1;

    t0 = tic;
    while toc(tic_start) < T_duration
        % Same sampled trajectory as the MATLAB simulation
        iteration = iteration + 1;
        n_samples = n_samples + 1;

        t_now = toc(tic_start);
        dt_used = compute_dt(t_now, last_time, iteration, dt);
        last_time = t_now;

        psi = atan2(sin(X_matlab(9,iteration)), cos(X_matlab(9,iteration)));

        drone.sendPositionSetpoint(X_matlab(1:3,iteration), psi);

        % Log measured state
        [pn, pe, pd] = drone.getPosition();
        [vn, ve, vd] = drone.getVelocity();
        [ph, th, ps] = drone.getEuler();
        [p, q, r] = drone.getAngularVelocity();

        X_drone(:,iteration) = ...
            [pn; pe; pd; vn; ve; vd; ph; th; ps; p; q; r];

        t_drone(iteration) = toc(t0);
        
        maintain_timing(tic_start, next_deadline);
        next_deadline = next_deadline + dt;

        % Real-time sampling period
        % while toc(t0) < k*Ts
        % end
    end


    % Final setpoint and landing
    psi = atan2(sin(X_matlab(9,end)), cos(X_matlab(9,end)));
    drone.sendPositionSetpoint(X_matlab(1:3,end), psi);

    pause(3);
    drone.land();
    pause(5);
    drone.disarm();
    drone.disconnect();
    Drone.shutdown();

catch ME
    fprintf(2, 'Errore deployment: %s\n', ME.message);

    if ~isempty(drone)
        try
            [pn, pe, pd] = drone.getPosition();
            drone.sendPositionSetpoint([pn; pe; pd], psi0);
            pause(2);
            drone.land();
            pause(5);
            drone.disarm();
            drone.disconnect();
        catch
        end
    end

    try
        Drone.shutdown();
    catch
    end

    rethrow(ME);
end


%% 4. SAVE LOG
save(sprintf('OpenLoop_Setpoints_%s_log.mat', SHAPE), ...
    't_ref', 'X_ref', 't_k', 'X_sample', 'U_sample', ...
    'X_matlab', 't_drone', 'X_drone', 'Ts', 'SHAPE');

%% 5. PLOT: REFERENCE VS MATLAB VS DRONE
valid = all(isfinite(X_drone(1:3,:)), 1);

figure('Name', ['Trajectory - ' SHAPE], ...
    'Color', 'w', 'Position', [100 100 1100 750]);

% XY trajectory
subplot(2,2,[1 3]);

plot(X_ref(2,:), X_ref(1,:), 'k--', 'LineWidth', 1.5);
hold on;

plot(X_matlab(2,:), X_matlab(1,:), 'b-', 'LineWidth', 1.3);

plot(X_drone(2,valid), X_drone(1,valid), ...
    'r-', 'LineWidth', 1.3);

plot(p0(2), p0(1), 'ko', 'MarkerFaceColor', 'k');

axis equal;
grid on;
xlabel('East [m]');
ylabel('North [m]');
title('Traiettoria XY');
legend('Reference (flatness)', 'MATLAB (ODE + ZOH)', ...
    'Drone', 'Start', 'Location', 'best');

% Position errors
subplot(2,2,2);

e_matlab = vecnorm( ...
    X_matlab(1:3,:) - interp1(t_ref, X_ref(1:3,:)', t_k)', 2, 1);

plot(t_k, e_matlab, 'b-', 'LineWidth', 1.3);
hold on;

if any(valid)
    e_drone = vecnorm( ...
        X_drone(1:3,valid) - ...
        interp1(t_ref, X_ref(1:3,:)', t_drone(valid))', 2, 1);

    plot(t_drone(valid), e_drone, 'r-', 'LineWidth', 1.3);
end

grid on;
xlabel('Time [s]');
ylabel('Position error [m]');
title('Errore rispetto alla reference');
legend('MATLAB', 'Drone', 'Location', 'best');

% Position versus time
subplot(2,2,4);

plot(t_ref, X_ref(1:3,:), 'k--', 'LineWidth', 1.2);
hold on;

plot(t_k, X_matlab(1:3,:), 'b-', 'LineWidth', 1.2);

if any(valid)
    plot(t_drone(valid), X_drone(1:3,valid), ...
        'r-', 'LineWidth', 1.2);
end

grid on;
xlabel('Time [s]');
ylabel('Position [m]');
title('Posizione nel tempo');
legend('N reference', 'E reference', 'D reference', ...
    'N MATLAB', 'E MATLAB', 'D MATLAB', ...
    'N drone', 'E drone', 'D drone', ...
    'Location', 'best');

sgtitle(sprintf('%s | Ts = %.2f s', SHAPE, Ts));

%% 6. GIF + PLOTDRONE
% Animated 3D comparison: reference, MATLAB, drone.

gifFile = sprintf('OpenLoop_%s.gif', SHAPE);

fig3 = figure('Name', ['3D Animation - ' SHAPE], ...
    'Color', 'w');

hold on;
grid on;
axis equal;
view(3);

plot3(X_ref(2,:), X_ref(1,:), -X_ref(3,:), ...
    'k--', 'LineWidth', 1.2);

h_matlab = animatedline('Color', 'b', 'LineWidth', 1.5);
h_drone  = animatedline('Color', 'r', 'LineWidth', 1.5);

xlabel('East [m]');
ylabel('North [m]');
zlabel('Altitude [m]');
title('Reference vs MATLAB vs drone');

% Align animation to the MATLAB sampling instants.
for k = 1:N+1
    addpoints(h_matlab, X_matlab(2,k), ...
        X_matlab(1,k), -X_matlab(3,k));

    if valid(k)
        addpoints(h_drone, X_drone(2,k), ...
            X_drone(1,k), -X_drone(3,k));
    end

    drawnow;

    frame = getframe(fig3);
    [im, map] = rgb2ind(frame.cdata, 256);

    if k == 1
        imwrite(im, map, gifFile, 'gif', ...
            'LoopCount', Inf, 'DelayTime', Ts);
    else
        imwrite(im, map, gifFile, 'gif', ...
            'WriteMode', 'append', 'DelayTime', Ts);
    end
end

